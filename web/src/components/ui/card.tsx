import * as React from 'react'
import { cn } from '@/lib/utils'

function Card({ className, ...props }: React.ComponentProps<'div'>) {
  return (
    <div
      data-slot="card"
      className={cn(
        'surface-card text-card-foreground flex flex-col gap-5 rounded-[var(--r-card)] py-5',
        className,
      )}
      {...props}
    />
  )
}

